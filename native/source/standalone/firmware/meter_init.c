#include "meter_init.h"
int mttl_meter_initialize(unsigned ch,mttl_meter_write write,void *context){
 static const struct {uint8_t reg,n,data[9];} sequence[]={
 {0x5f,9,{3,0xd0,0x90,0x0a,0x2d,0x25,0x7f,0x34,0x4f}},
 {0x80,6,{0x5e,0x19,0,0,0,0x56}}, {0,3,{0,0,0x14}},
 {0x59,3,{0,0x0f,0xa0}}, {0x49,3,{0xfd,0xa5,0xff}},
 {0x4a,3,{0,0x61,0xa8}}, {0x4b,3,{0x40,0,0}},
 {0x4c,3,{0x40,0,0}}, {0x4d,3,{1,0xf4,0}},
 {0x4e,3,{1,0xd4,0xc0}}, {0x4f,3,{0,0,5}}};
 static const uint8_t offset34[]={0xfd,0xc0,0xc8};
 static const uint8_t calibration[4][6]={{0x20,0x67,0x31,0x20,0xf3,0x0b},{0x1f,0xfc,0x37,0x20,0xf2,0xab},{0x20,0x49,0xd2,0x20,0xf9,0xd9},{0x20,5,0x72,0x20,0xfa,0x1c}};
 unsigned i;if(ch>=4||!write)return 0;
 for(i=0;i<sizeof(sequence)/sizeof(sequence[0]);i++){const uint8_t *data=sequence[i].data;if(sequence[i].reg==0x49&&ch>=2)data=offset34;if(write(context,ch,sequence[i].reg,data,sequence[i].n)!=1)return 0;}
 return write(context,ch,0x50,calibration[ch],6)==1;
}
